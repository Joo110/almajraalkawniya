// 1. انسخ عنصر كامل من المصفوفة partners (من { لحد }) والصقه قبل الـ ]
// 2. غيّر id (لازم يكون فريد ومكتوب بحروف انجليزية بدون مسافات)
// 3. غيّر name (اسم الشركة اللي هيظهر للزوار)
// 4. ضيف الصور جوه offers

